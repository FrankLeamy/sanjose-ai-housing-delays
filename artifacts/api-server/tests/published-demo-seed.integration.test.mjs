import assert from "node:assert/strict";
import test from "node:test";
import pg from "pg";
import { buildAccountSeed } from "../scripts/export-published-demo-accounts.mjs";

// This explicit opt-in checks only connection-local temporary rows, never users.
const enabled = process.env.RUN_SEED_SQL_TESTS === "1";
const fixtures = () => [
  { username: "city_staff_reviewer", role: "city_staff_admin", is_demo: true, display_name: "Staff", email: "staff@example.test", password_hash: "$2b$12$" + "A".repeat(53) },
  { username: "resident1", role: "resident", is_demo: true, display_name: "Resident", email: "resident@example.test", password_hash: "$2b$12$" + "B".repeat(53) },
];
const seedSql = (accounts) => buildAccountSeed(accounts).replaceAll("public.users", "pg_temp.users");

test("Seed SQL creates accounts, reruns without changes, and rolls back identity conflicts", { skip: !enabled }, async () => {
  assert.equal(process.env.NODE_ENV, "development");
  assert.ok(process.env.REPLIT_DEV_DOMAIN);
  assert.ok(!process.env.REPLIT_DEPLOYMENT);
  const db = new pg.Client({ connectionString: process.env.DATABASE_URL });
  try {
    await db.connect();
    // Exact production column types, defaults and unique constraints. The ID
    // default uses a temporary identity sequence, not the real users_id_seq.
    await db.query(`CREATE TEMP TABLE users (
      id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
      username text NOT NULL UNIQUE,
      password_hash text NOT NULL,
      created_at timestamptz NOT NULL DEFAULT now(),
      role public.user_role NOT NULL DEFAULT 'resident'::public.user_role,
      is_demo boolean NOT NULL DEFAULT false,
      display_name text,
      email text
    )`);
    for (const role of ["city_staff_admin", "staff", "admin"]) {
      await db.query("TRUNCATE pg_temp.users RESTART IDENTITY");
      const accounts = fixtures();
      accounts[0].role = role;
      await db.query(seedSql(accounts));
      const first = (await db.query("SELECT * FROM pg_temp.users ORDER BY username")).rows;
      assert.equal(first.length, 2);
      for (const row of first) {
        const expected = accounts.find((account) => account.username === row.username);
        for (const column of ["role", "password_hash", "email", "display_name", "is_demo"]) {
          assert.equal(row[column], expected[column]);
        }
        assert.ok(Number.isInteger(row.id));
        assert.ok(row.created_at instanceof Date);
      }
      await db.query(seedSql(accounts));
      assert.deepEqual((await db.query("SELECT * FROM pg_temp.users ORDER BY username")).rows, first);
    }
    for (const change of [
      { username: "other_account", email: "STAFF@example.test" },
      { role: "resident" },
      { password_hash: "$2b$12$" + "C".repeat(53) },
      { is_demo: false },
      { email: "different@example.test" },
    ]) {
      await db.query("TRUNCATE pg_temp.users RESTART IDENTITY");
      const conflict = { ...fixtures()[0], ...change };
      await db.query(
        "INSERT INTO pg_temp.users (username, password_hash, role, display_name, email, is_demo) VALUES ($1, $2, $3::public.user_role, $4, $5, $6)",
        [conflict.username, conflict.password_hash, conflict.role, conflict.display_name, conflict.email, conflict.is_demo],
      );
      const before = (await db.query("SELECT * FROM pg_temp.users ORDER BY username")).rows;
      await assert.rejects(db.query(seedSql(fixtures())), { code: "P0001" });
      await db.query("ROLLBACK");
      assert.deepEqual((await db.query("SELECT * FROM pg_temp.users ORDER BY username")).rows, before);
    }
    await db.query("TRUNCATE pg_temp.users RESTART IDENTITY");
    const quoted = fixtures();
    quoted[1].email = "resident$demo_seed_guard$'quoted@example.test";
    quoted[1].display_name = "Resident's \\ profile";
    await db.query(seedSql(quoted));
    const resident = (await db.query("SELECT email, display_name FROM pg_temp.users WHERE username = $1", ["resident1"])).rows[0];
    assert.equal(resident.email, quoted[1].email);
    assert.equal(resident.display_name, quoted[1].display_name);
  } finally {
    await db.end();
  }
});